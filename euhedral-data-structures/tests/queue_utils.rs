#[test]
fn unsigned_multiply_high_matches_upstream() {
    for &(a, b, expected) in MULTIPLY_HIGH {
        assert_eq!(unsigned_multiply_high(a, b), expected, "{a:#x} * {b:#x}");
    }
}

#[test]
fn unsigned_multiply_high_maps_a_seed_uniformly_onto_a_range() {
    // Used to pick a partition: seed * partitions >> 64 stays inside 0..partitions.
    for partitions in [1_u64, 2, 3, 7, 64] {
        assert_eq!(unsigned_multiply_high(0, partitions), 0);
        assert_eq!(unsigned_multiply_high(u64::MAX, partitions), partitions - 1);
    }
}

#[test]
fn round_chunk_size_rounds_up_to_a_power_of_two() {
    let expected: &[(u64, u64)] = &[
        (2, 2),
        (3, 4),
        (4, 4),
        (5, 8),
        (7, 8),
        (8, 8),
        (9, 16),
        (15, 16),
        (16, 16),
        (17, 32),
        (1000, 1024),
        (1024, 1024),
        (1025, 2048),
    ];
    for &(size, rounded) in expected {
        assert_eq!(round_chunk_size(size), rounded, "chunk size {size}");
    }
}

#[test]
fn round_chunk_size_is_capped_at_max_size() {
    assert_eq!(MAX_SIZE, 1 << 30);
    for size in [(1_u64 << 30) - 1, 1 << 30, (1 << 30) + 1, 1 << 40, u64::MAX] {
        assert_eq!(round_chunk_size(size), MAX_SIZE, "chunk size {size}");
    }
}

#[test]
fn round_chunk_size_of_one_is_one() {
    // Upstream returned 0 here, which made the mask -2.
    assert_eq!(round_chunk_size(1), 1);
    assert_eq!(chunk_mask(1), 0);
}

#[test]
#[should_panic(expected = "chunk size must be positive")]
fn round_chunk_size_rejects_zero() {
    round_chunk_size(0);
}

#[test]
fn chunk_mask_covers_the_rounded_size_minus_one_slots_in_counter_units() {
    // Counters advance by 2 per element, so the mask is (rounded - 1) << 1.
    let expected: &[(u64, u64)] = &[(2, 0x2), (3, 0x6), (4, 0x6), (8, 0xe), (100, 0xfe)];
    for &(size, mask) in expected {
        assert_eq!(chunk_mask(size), mask, "chunk size {size}");
    }
}
